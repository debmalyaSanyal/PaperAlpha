// Generate lib/db/schema-sqlite.ts from prisma/schema.sql.
//
// Why: Netlify runs Next.js routes inside serverless lambdas whose filesystem
// is read-only except /tmp, and /tmp starts empty on every cold start. Prisma's
// CLI (`prisma db push`) exists only at build time, so the runtime needs a
// bundled copy of the DDL to create its SQLite tables at request time.
// Embedding the SQL as a TypeScript module guarantees it is traced into the
// lambda bundle (importing a .sql file would not be).
//
// Usage: npm run db:sql
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const sqlPath = path.join(root, "prisma", "schema.sql");
const outPath = path.join(root, "lib", "generated", "sqlite-schema.ts");

const sql = readFileSync(sqlPath, "utf8");

const statements = sql
  .split(/;[\t ]*(?:\r?\n|$)/)
  .map((s) => s.trim())
  .filter(Boolean)
  .map((s) => (s.endsWith(";") ? s : `${s};`));

if (statements.length === 0) {
  throw new Error(`No statements parsed from ${sqlPath}`);
}

const body = statements
  .map((statement) => {
    const escaped = statement.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
    return `  \`${escaped}\`,`;
  })
  .join("\n");

const output = `// AUTO-GENERATED by scripts/embed-sqlite-schema.mjs - do not edit by hand.
// Source of truth: prisma/schema.sql (generated from prisma/schema.prisma).
// Regenerate with: npm run db:sql
//
// Used by lib/db.ts to create SQLite tables inside a writable runtime
// directory (e.g. /tmp on Netlify) when the database file does not exist yet.

export const SQLITE_SCHEMA_STATEMENTS: readonly string[] = [
${body}
];
`;

mkdirSync(path.dirname(outPath), { recursive: true });
writeFileSync(outPath, output, "utf8");
console.log(`Wrote ${path.relative(root, outPath)} (${statements.length} statements)`);
